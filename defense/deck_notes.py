def _block(H, ref):
    """ref: "TAG:IDX", a flat "18:Pn" key, or either with @a:b sentence slice."""
    slice_ = None
    if "@" in ref:
        ref, sl = ref.split("@", 1)
        a, b = sl.split(":")
        slice_ = (int(a), int(b))
    if ref in H:
        txt = H[ref]["blocks"][0]
    else:
        tag, idx = ref.rsplit(":", 1)
        txt = H[tag]["blocks"][int(idx)]
    txt = txt.replace("\n", " ").strip()
    if slice_:
        ss = re.split(r"(?<=[.؟!])\s+", txt)
        txt = " ".join(ss[slice_[0]:slice_[1]])
    return txt


def build():
    H = json.loads(JS.read_text(encoding="utf-8"))
    out = {}
    for i in range(1, 25):
        parts = ["— محور اسلاید —", LEAD[i], "", "— شرح و شاهد —"]
        for ref in BODY.get(i, []):
            blk = _block(H, ref)
            blk = re.sub(r"^[«\"]\s*", "", blk)
            blk = re.sub(r"[»\"]\s*$", "", blk)
            parts.append(blk)
        if QA.get(i):
            parts.append("")
            parts.append("— پرسش‌های محتمل داور —")
            for tag in QA[i]:
                d = H[tag]
                ans = " ".join(b.replace("\n", " ").strip() for b in d["blocks"])
                parts.append("پرسش: " + d["title"] + "  پاسخ: " + ans)
        out[i] = "\n".join(parts)
    return out


