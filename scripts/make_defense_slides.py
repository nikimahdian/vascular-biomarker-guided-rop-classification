def rtl(p, align=PP_ALIGN.RIGHT):
    pPr = p._p.get_or_add_pPr()
    pPr.set("rtl", "1")
    p.alignment = align
    return p


def box(slide, l, t, w, h):
    tb = slide.shapes.add_textbox(Inches(l), Inches(t), Inches(w), Inches(h))
    tf = tb.text_frame
    tf.word_wrap = True
    return tf


def title_bar(slide, text, sub=None):
    bar = slide.shapes.add_shape(1, Inches(0), Inches(0), prs.slide_width, Inches(1.15))
    bar.fill.solid(); bar.fill.fore_color.rgb = NAVY; bar.line.fill.background()
    bar.shadow.inherit = False
    tf = bar.text_frame
    tf.margin_right = Inches(0.45); tf.margin_left = Inches(0.45)
    tf.vertical_anchor = MSO_ANCHOR.MIDDLE
    p = tf.paragraphs[0]
    p.text = text
    rtl(p)
    p.runs[0].font.size = Pt(30); p.runs[0].font.bold = True
    p.runs[0].font.color.rgb = RGBColor(0xFF, 0xFF, 0xFF); p.runs[0].font.name = FONT
    if sub:
        tf2 = box(slide, 0.6, 1.25, 12.1, 0.5)
        p2 = tf2.paragraphs[0]; p2.text = sub; rtl(p2)
        p2.runs[0].font.size = Pt(17); p2.runs[0].font.color.rgb = GREY; p2.runs[0].font.name = FONT


def bullets(slide, items, top=1.95, left=0.7, width=12.0, size=20, height=5.0):
    tf = box(slide, left, top, width, height)
    first = True
    for it in items:
        lvl = 0
        if isinstance(it, tuple):
            it, lvl = it
        p = tf.paragraphs[0] if first else tf.add_paragraph()
        first = False
        p.text = ("• " if lvl == 0 else "– ") + it
        rtl(p)
        p.space_after = Pt(10 if lvl == 0 else 6)
        for r in p.runs:
            r.font.size = Pt(size if lvl == 0 else size - 3)
            r.font.name = FONT
            r.font.color.rgb = NAVY if lvl == 0 else GREY
        p.level = lvl


def picture_slide(title, img, caption, bullets_list=None, sub=None):
    s = prs.slides.add_slide(BLANK)
    title_bar(s, title, sub)
    path = FIG / img
    if bullets_list:
        bullets(s, bullets_list, top=1.95, left=7.5, width=5.2, size=17)
        s.shapes.add_picture(str(path), Inches(0.55), Inches(1.9), width=Inches(6.75))
    else:
        s.shapes.add_picture(str(path), Inches(1.3), Inches(1.75), width=Inches(10.7))
    tf = box(s, 1.0, 6.72, 11.3, 0.6)
    p = tf.paragraphs[0]; p.text = caption; rtl(p, PP_ALIGN.CENTER)
    p.runs[0].font.size = Pt(14); p.runs[0].font.italic = True
    p.runs[0].font.color.rgb = GREY; p.runs[0].font.name = FONT
    return s


def notes(slide, text):
    slide.notes_slide.notes_text_frame.text = text


def table_slide(title, headers, rows, caption, col_w=None, size=13):
    s = prs.slides.add_slide(BLANK)
    title_bar(s, title)
    n_r, n_c = len(rows) + 1, len(headers)
    tbl_shape = s.shapes.add_table(n_r, n_c, Inches(0.5), Inches(1.5),
                                   Inches(12.3), Inches(0.42 * n_r))
    tbl = tbl_shape.table
    if col_w:
        total = sum(col_w)
        for i, w in enumerate(col_w):
            tbl.columns[i].width = Emu(int(Inches(12.3) * w / total))
    for j, h in enumerate(headers):
        c = tbl.cell(0, j)
        c.text = h
        for p in c.text_frame.paragraphs:
            rtl(p, PP_ALIGN.CENTER)
            for r in p.runs:
                r.font.size = Pt(size); r.font.bold = True
                r.font.color.rgb = RGBColor(0xFF, 0xFF, 0xFF); r.font.name = FONT
        c.fill.solid(); c.fill.fore_color.rgb = NAVY
    for i, row in enumerate(rows, start=1):
        for j, v in enumerate(row):
            c = tbl.cell(i, j); c.text = str(v)
            for p in c.text_frame.paragraphs:
                rtl(p, PP_ALIGN.CENTER)
                for r in p.runs:
                    r.font.size = Pt(size); r.font.name = FONT; r.font.color.rgb = NAVY
            c.fill.solid()
            c.fill.fore_color.rgb = RGBColor(0xFF, 0xFF, 0xFF) if i % 2 else LIGHT
    tf = box(s, 0.8, 1.5 + 0.44 * n_r + 0.15, 11.7, 0.8)
    p = tf.paragraphs[0]; p.text = caption; rtl(p)
    p.runs[0].font.size = Pt(13); p.runs[0].font.italic = True
    p.runs[0].font.color.rgb = GREY; p.runs[0].font.name = FONT
    return s


